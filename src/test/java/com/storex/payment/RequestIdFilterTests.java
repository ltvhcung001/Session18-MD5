package com.storex.payment;

import org.junit.jupiter.api.Test;
import org.slf4j.MDC;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.notNullValue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
class RequestIdFilterTests {

    @Autowired
    private MockMvc mockMvc;

    @Test
    void testAutoGeneratedRequestIdInHeader() throws Exception {
        // Gửi request không có header X-Request-Id
        MvcResult result = mockMvc.perform(get("/api/orders/fail-demo"))
                .andExpect(status().isOk())
                .andExpect(header().exists("X-Request-Id"))
                .andReturn();

        String requestIdHeader = result.getResponse().getHeader("X-Request-Id");
        assertThat(requestIdHeader).isNotNull();

        // Kiểm tra requestId là UUID hợp lệ
        UUID parsedUuid = UUID.fromString(requestIdHeader);
        assertThat(parsedUuid).isNotNull();

        // Kiểm tra sau khi request kết thúc, MDC đã được dọn sạch khỏi thread
        assertThat(MDC.get("requestId")).isNull();
    }

    @Test
    void testPropagatedRequestIdInHeader() throws Exception {
        String customRequestId = "CLIENT-TRACE-XYZ-9999";

        // Gửi request có sẵn header X-Request-Id
        mockMvc.perform(get("/api/orders/fail-demo")
                        .header("X-Request-Id", customRequestId))
                .andExpect(status().isOk())
                .andExpect(header().string("X-Request-Id", customRequestId));

        // Kiểm tra sau khi request kết thúc, MDC đã được dọn sạch khỏi thread
        assertThat(MDC.get("requestId")).isNull();
    }
}
